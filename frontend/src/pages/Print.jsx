// Print-ready documents, shown outside the app shell: study notes and assessment reports.
// They open the browser's print dialog, where "Save as PDF" produces the exported file.
import { Check, Download, FileDown, Lightbulb, Sigma, Star, X } from "lucide-react";
import { useEffect, useMemo, useRef, useState } from "react";
import { useParams, useSearchParams } from "react-router-dom";

import { InlineMarkdown, Loading, Markdown } from "../components/ui.jsx";
import { useApp } from "../context/AppContext.jsx";
import { api } from "../lib/api.js";
import { parseNotes, segments } from "./Library.jsx";

const KEYS = ["A", "B", "C", "D"];
const CALLOUT_ICONS = { example: Lightbulb, note: Star, formula: Sigma };
const CALLOUT_LABELS = { example: "Example", note: "Remember", formula: "Formula" };

const longDate = (value = new Date()) => new Date(value).toLocaleDateString(undefined, { day: "numeric", month: "long", year: "numeric" });

function usePrintOnce(ready, title) {
  const [params] = useSearchParams();
  const done = useRef(false);
  useEffect(() => {
    if (!ready) return undefined;
    document.title = title;
    if (done.current || params.get("print") === "0") return undefined;
    done.current = true;
    // Wait for fonts and maths to settle so the PDF matches the screen.
    const timer = setTimeout(() => (document.fonts?.ready || Promise.resolve()).then(() => window.print()), 450);
    return () => clearTimeout(timer);
  }, [ready, title, params]);
}

function Toolbar({ children }) {
  return (
    <div className="print-toolbar no-print">
      <span className="brand-mark" aria-hidden="true">त</span>
      <strong>Export</strong>
      <span className="hint">Choose “Save as PDF” as the printer to download the file.</span>
      <span className="spacer" />
      {children}
      <button className="btn" type="button" onClick={() => window.print()}><FileDown size={15} /> Save as PDF</button>
      <button className="btn btn-ghost" type="button" onClick={() => window.close()}><X size={15} /> Close</button>
    </div>
  );
}

function Cover({ kind, title, subtitle, tone, rows }) {
  return (
    <header className="pd-cover" style={{ "--tone": tone }}>
      <div className="pd-brand">
        <span className="pd-mark" aria-hidden="true">त</span>
        <span><b>TatvaX</b><small>Multilingual AI tutor</small></span>
        <span className="pd-kind">{kind}</span>
      </div>
      <h1>{title}</h1>
      {subtitle && <p className="pd-sub">{subtitle}</p>}
      <dl className="pd-meta">
        {rows.filter(([, value]) => value != null && value !== "").map(([label, value]) => (
          <div key={label}><dt>{label}</dt><dd>{value}</dd></div>
        ))}
      </dl>
    </header>
  );
}

function Footer() {
  const { app } = useApp();
  return <footer className="pd-footer">Generated by TatvaX {app.version} on {longDate()}. For personal study use.</footer>;
}

function studentName(user) {
  return user && !user.is_guest ? user.name : "Guest learner";
}

// ------------------------------------------------------------------ notes

export function PrintNotes() {
  const { slug } = useParams();
  const { user } = useApp();
  const [doc, setDoc] = useState(null);
  const [error, setError] = useState("");

  useEffect(() => {
    api(`/api/library/${encodeURIComponent(slug)}`).then((res) => setDoc(res.document)).catch((err) => setError(err.message));
  }, [slug]);

  const chapters = useMemo(() => (doc ? parseNotes(doc.body) : []), [doc]);
  usePrintOnce(Boolean(doc), doc ? `${doc.title} - Study notes - TatvaX` : "TatvaX");

  const downloadMarkdown = () => {
    const blob = new Blob([`# ${doc.title}\n\n${doc.description || ""}\n\n${doc.body}`], { type: "text/markdown;charset=utf-8" });
    const link = document.createElement("a");
    link.href = URL.createObjectURL(blob);
    link.download = `${doc.slug}-notes.md`;
    link.click();
    setTimeout(() => URL.revokeObjectURL(link.href), 1000);
  };

  if (error) return <div className="print-error">{error}</div>;
  if (!doc) return <Loading label="Preparing your notes" />;
  const topics = chapters.reduce((n, c) => n + c.topics.length, 0);

  return (
    <div className="print-page">
      <Toolbar><button className="btn btn-secondary" type="button" onClick={downloadMarkdown}><Download size={15} /> Markdown</button></Toolbar>
      <article className="print-doc">
        <Cover kind="Study notes" title={doc.title} subtitle={doc.description} tone={doc.color}
          rows={[["Prepared for", studentName(user)], ["Class", user?.grade ? `Class ${user.grade}` : null],
            ["Chapters", chapters.length], ["Topics", topics], ["Date", longDate()]]} />

        <section className="pd-toc">
          <h2>Contents</h2>
          <ol>
            {chapters.map((c, i) => <li key={i}><span>{c.title}</span><small>{c.topics.length} topics</small></li>)}
          </ol>
        </section>

        {chapters.map((chapter, i) => (
          <section key={i} className="pd-chapter" style={{ "--tone": doc.color }}>
            <h2><span className="pd-num">{chapter.number}</span>{chapter.title}</h2>
            {chapter.intro.join("\n").trim() && <Markdown source={chapter.intro.join("\n")} />}
            {chapter.topics.map((topic, j) => (
              <div key={j} className="pd-topic">
                <h3>{topic.title}</h3>
                {segments(topic.lines).map((seg, k) => {
                  if (seg.kind === "md") return <Markdown key={k} source={seg.lines.join("\n")} />;
                  const Icon = CALLOUT_ICONS[seg.kind];
                  return (
                    <div key={k} className={`pd-callout ${seg.kind}`}>
                      <span className="pd-callout-label"><Icon size={13} /> {CALLOUT_LABELS[seg.kind]}</span>
                      <Markdown source={seg.lines.join("\n")} />
                    </div>
                  );
                })}
              </div>
            ))}
          </section>
        ))}
        <Footer />
      </article>
    </div>
  );
}

// ------------------------------------------------------------------ assessment report

function band(percent) {
  if (percent >= 90) return ["Outstanding", "#2f8a3c"];
  if (percent >= 75) return ["Very good", "#0e9f8e"];
  if (percent >= 60) return ["Good", "#4f63e0"];
  if (percent >= 40) return ["Needs practice", "#c98a0c"];
  return ["Keep going", "#d4513e"];
}

const formatDuration = (s) => (s == null ? null : `${Math.floor(s / 60)} min ${String(s % 60).padStart(2, "0")} s`);

export function PrintAssessment() {
  const { id } = useParams();
  const { user, languageInfo } = useApp();
  const [quiz, setQuiz] = useState(null);
  const [error, setError] = useState("");

  useEffect(() => {
    api(`/api/quiz/${id}`).then((res) => setQuiz(res.quiz)).catch((err) => setError(err.message));
  }, [id]);

  usePrintOnce(Boolean(quiz), quiz ? `${quiz.subject_title} assessment report - TatvaX` : "TatvaX");

  if (error) return <div className="print-error">{error}</div>;
  if (!quiz) return <Loading label="Preparing your report" />;

  const finished = quiz.finished;
  const results = finished?.results || [];
  const percent = finished ? Math.round((100 * finished.score) / finished.total) : null;
  const [label, color] = percent != null ? band(percent) : ["", ""];
  const wrong = results.filter((r) => !r.correct).length;
  const skipped = results.filter((r) => r.choice == null).length;
  const tone = quiz.subjects[0]?.color || "#0f5a57";

  return (
    <div className="print-page">
      <Toolbar />
      <article className="print-doc">
        <Cover kind={finished ? "Assessment report" : "Question paper"} title={quiz.subject_title}
          subtitle={quiz.topic ? `Topic: ${quiz.topic}` : "Multiple-choice assessment"} tone={tone}
          rows={[["Student", studentName(user)], ["Class", user?.grade ? `Class ${user.grade}` : null],
            ["Date", longDate(quiz.completed_at || quiz.created_at)], ["Mode", quiz.mode[0].toUpperCase() + quiz.mode.slice(1)],
            ["Difficulty", quiz.difficulty[0].toUpperCase() + quiz.difficulty.slice(1)], ["Questions", quiz.questions.length],
            ["Language", languageInfo(quiz.language)?.name]]} />

        {finished && (
          <section className="pd-report">
            <h2>Performance report</h2>
            <div className="pd-score">
              <div className="pd-score-big" style={{ "--band": color }}>
                <b>{percent}%</b>
                <span>{finished.score} of {finished.total} correct</span>
                <em>{label}</em>
              </div>
              <dl className="pd-facts">
                <div><dt>Correct</dt><dd>{finished.score}</dd></div>
                <div><dt>Incorrect</dt><dd>{wrong - skipped}</dd></div>
                <div><dt>Skipped</dt><dd>{skipped}</dd></div>
                <div><dt>Time taken</dt><dd>{formatDuration(finished.duration_s) || "—"}</dd></div>
              </dl>
            </div>
            <div className="pd-strip" aria-label="Answers at a glance">
              {results.map((r, i) => <span key={i} className={r.correct ? "ok" : r.choice == null ? "skip" : "bad"}>{i + 1}</span>)}
            </div>
            {finished.breakdown?.length > 0 && (
              <table className="pd-table">
                <thead><tr><th>Subject</th><th>Correct</th><th>Total</th><th>Score</th></tr></thead>
                <tbody>
                  {finished.breakdown.map((b) => (
                    <tr key={b.subject}>
                      <td>{b.subject || quiz.subject_title}</td><td>{b.correct}</td><td>{b.total}</td>
                      <td><span className="pd-bar"><span style={{ width: `${(100 * b.correct) / b.total}%` }} /></span>{Math.round((100 * b.correct) / b.total)}%</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )}
          </section>
        )}

        <section className="pd-questions">
          <h2>{finished ? "Questions and answers" : "Questions"}</h2>
          {quiz.questions.map((q, i) => {
            const r = results[i];
            return (
              <div key={i} className={`pd-q${r ? (r.correct ? " ok" : " bad") : ""}`}>
                <div className="pd-q-head">
                  <span className="pd-qnum">Q{i + 1}</span>
                  {q.subject_title && quiz.subjects.length > 1 && <span className="pd-qsub">{q.subject_title}</span>}
                  {r && <span className="pd-verdict">{r.correct ? "Correct" : r.choice == null ? "Not answered" : "Incorrect"}</span>}
                </div>
                <Markdown className="prose pd-qtext" source={q.question} />
                <ol className="pd-options">
                  {q.options.map((option, j) => {
                    const isAnswer = r && j === r.answer_index;
                    const isChoice = r && j === r.choice;
                    return (
                      <li key={j} className={`${isAnswer ? "answer" : ""}${isChoice && !isAnswer ? " chosen" : ""}`}>
                        <span className="pd-key">{KEYS[j]}</span>
                        <InlineMarkdown source={option} />
                        {isAnswer && <span className="pd-tag"><Check size={11} /> Correct answer</span>}
                        {isChoice && !isAnswer && <span className="pd-tag bad">Your answer</span>}
                        {isChoice && isAnswer && <span className="pd-tag">Your answer</span>}
                      </li>
                    );
                  })}
                </ol>
                {r?.explanation && <div className="pd-explain"><b>Explanation</b><InlineMarkdown source={r.explanation} /></div>}
              </div>
            );
          })}
        </section>
        <Footer />
      </article>
    </div>
  );
}

// ------------------------------------------------------------------ progress report

const pct = (n, d) => (d ? Math.round((100 * n) / d) : 0);

function ProgressReport({ report, forTeacher }) {
  const r = report;
  const maxDay = Math.max(1, ...r.activity.map((d) => d.questions + d.quizzes));
  const accuracy = pct(r.totals.correct, r.totals.answered);
  return (
    <article className="print-doc">
      <Cover kind="Progress report" title={r.student.name} subtitle={forTeacher ? "Learning summary for parents and teachers" : "My learning summary"}
        tone="#0f5a57"
        rows={[["Class", r.student.grade ? `Class ${r.student.grade}` : null], ["Level", `${r.level} (${r.xp} XP)`],
          ["Streak", `${r.streak.current} days (best ${r.streak.best})`], ["Learning since", longDate(r.student.joined)],
          ["Report date", longDate(`${r.generated}T12:00:00`)]]} />

      <section className="pd-report">
        <h2>At a glance</h2>
        <dl className="pd-facts four">
          <div><dt>Questions asked</dt><dd>{r.totals.questions}</dd></div>
          <div><dt>Assessments</dt><dd>{r.totals.assessments}</dd></div>
          <div><dt>Average score</dt><dd>{r.totals.average != null ? `${r.totals.average}%` : "—"}</dd></div>
          <div><dt>Answers correct</dt><dd>{r.totals.answered ? `${accuracy}%` : "—"}</dd></div>
          <div><dt>Active days (30)</dt><dd>{r.totals.active_days}</dd></div>
          <div><dt>Badges</dt><dd>{r.badges.length}/{r.badges_total}</dd></div>
          <div><dt>Review deck</dt><dd>{r.review.mastered}/{r.review.total} mastered</dd></div>
          <div><dt>Assignments</dt><dd>{r.totals.assigned ? `${r.totals.assigned_done}/${r.totals.assigned}` : "—"}</dd></div>
        </dl>
        {(r.strongest || r.needs_work) && (
          <p className="pd-note">
            {r.strongest && <>Strongest subject: <b>{r.strongest}</b>. </>}
            {r.needs_work && <>Most room to grow: <b>{r.needs_work}</b>, so extra practice there will help most.</>}
          </p>
        )}

        <h3 className="pd-h3">Activity over the last 30 days</h3>
        <div className="pd-activity" aria-label="Activity per day">
          {r.activity.map((d) => (
            <span key={d.day} title={`${d.day}: ${d.questions} questions, ${d.quizzes} assessments`}>
              <i style={{ height: `${((d.questions + d.quizzes) / maxDay) * 100}%` }} />
            </span>
          ))}
        </div>
        <div className="pd-activity-axis"><span>{r.activity[0].day}</span><span>{r.activity[r.activity.length - 1].day}</span></div>

        <h3 className="pd-h3">Subjects</h3>
        <table className="pd-table">
          <thead><tr><th>Subject</th><th>Questions</th><th>Assessments</th><th>Average</th><th>Best</th><th>To review</th></tr></thead>
          <tbody>
            {r.subjects.map((s) => (
              <tr key={s.slug}>
                <td><span className="pd-dot" style={{ background: s.color }} />{s.title}</td>
                <td>{s.questions}</td><td>{s.assessments}</td>
                <td>{s.average != null ? <><span className="pd-bar"><span style={{ width: `${s.average}%`, background: s.color }} /></span>{s.average}%</> : "—"}</td>
                <td>{s.best != null ? `${s.best}%` : "—"}</td><td>{s.to_review}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>

      {r.recent.length > 0 && (
        <section className="pd-report">
          <h2>Recent assessments</h2>
          <table className="pd-table">
            <thead><tr><th>Date</th><th>Subject</th><th>Mode</th><th>Score</th></tr></thead>
            <tbody>
              {r.recent.map((q) => (
                <tr key={q.id}>
                  <td>{new Date(q.completed_at).toLocaleDateString(undefined, { day: "numeric", month: "short" })}</td>
                  <td>{q.subject}{q.topic ? `: ${q.topic}` : ""}</td>
                  <td style={{ textTransform: "capitalize" }}>{q.mode}</td>
                  <td><b>{q.score}/{q.total}</b> ({pct(q.score, q.total)}%)</td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      )}

      {r.badges.length > 0 && (
        <section className="pd-report">
          <h2>Badges earned</h2>
          <ul className="pd-badges">{r.badges.map((b) => <li key={b.id}><b>{b.name}</b><span>{b.description}</span></li>)}</ul>
        </section>
      )}
      <Footer />
    </article>
  );
}

function ReportPage({ path, forTeacher }) {
  const [report, setReport] = useState(null);
  const [error, setError] = useState("");
  useEffect(() => { api(path).then((res) => setReport(res.report)).catch((err) => setError(err.message)); }, [path]);
  usePrintOnce(Boolean(report), report ? `${report.student.name} - Progress report - TatvaX` : "TatvaX");
  if (error) return <div className="print-error">{error}</div>;
  if (!report) return <Loading label="Preparing the report" />;
  return (
    <div className="print-page">
      <Toolbar />
      <ProgressReport report={report} forTeacher={forTeacher} />
    </div>
  );
}

